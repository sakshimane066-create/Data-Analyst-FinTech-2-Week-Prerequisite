out = ["# Data Dictionary: Bluestock MF Analytics", "",
 "Database: `bluestock_mf.db` (SQLite star schema, DDL in `schema.sql`). Cleaned CSVs are in `data/processed/`.", "",
 "## Conventions", "",
 "- **1 lakh** = 100,000 and **1 crore** = 10,000,000. **1 lakh crore** = 1,000,000,000,000 rupees.",
 "- **Dates** are text `YYYY-MM-DD` in CSVs. In the database every fact joins to `dim_date` through `date_key` (integer `YYYYMMDD`).",
 "- **Money** columns are in rupees unless the column name says `crore` or `lakh`.",
 "- **Star schema:** `dim_fund` and `dim_date` describe; `fact_*` tables hold measurements. Supporting tables are industry-level or fund-level extras that also link to `dim_date` / `dim_fund`.", "",
 "## Table overview", "", "| Table | Type | Grain | Source file |", "|---|---|---|---|"]
for t, (title, src, grain, _) in D.items():
    kind = "Dimension" if t.startswith("dim_") else ("Fact" if t.startswith("fact_") else "Supporting")
    out.append(f"| `{t}` | {kind} | {grain} | {src} |")

for t, (title, src, grain, cols) in D.items():
    info = conn.execute(f"PRAGMA table_info({t})").fetchall()
    out += ["", f"## {t}: {title}", "", f"**Source:** {src}  |  **Grain:** {grain}", "",
            "| Column | Type | Key | Definition |", "|---|---|---|---|"]
    fks = {r[3]: f"{r[2]}.{r[4]}" for r in conn.execute(f"PRAGMA foreign_key_list({t})")}
    for _, name, typ, notnull, _, pk in info:
        key = ("PK" if pk else "") + (", " if pk and name in fks else "") + (f"FK to {fks[name]}" if name in fks else "")
        out.append(f"| `{name}` | {typ} | {key} | {cols.get(name, '(added automatically from the cleaned CSV)')} |")

out += ["", "## Cleaning rules applied (clean_data.py)", "",
 "| Dataset | Rule |", "|---|---|",
 "| nav_history | Parse dates; sort by amfi_code + date; remove duplicate (amfi_code, date); drop NAV <= 0; forward-fill weekends/holidays to a daily calendar and mark them `is_filled = 1`. |",
 "| investor_transactions | Standardise transaction_type to SIP/Lumpsum/Redemption; drop amount <= 0; parse dates; keep only kyc_status in Verified/Pending/Rejected; remove duplicates. |",
 "| scheme_performance | Coerce return/ratio columns to numeric; flag outliers with a 3 x IQR rule, compared within each asset class (Equity vs Debt) so debt funds are not judged against equity funds (`has_anomaly`, `anomaly_columns`); flag expense ratio outside 0.1-2.5% (all 40 pass). |",
 "| fund_master | Parse launch_date; numeric checks; flag expense_ratio_pct outside 0.1-2.5 (all 40 funds pass). |",
 "| All others | Parse dates, numeric checks, remove duplicates on the natural key, reject negative amounts. |", "",
 "Every action and the number of rows it affected is recorded in `data/processed/cleaning_day2_log.csv`.", "",
 "## Known limitations", "",
 "- `nav_history` has 46,000 real NAV rows; forward-filling adds 18,320 weekend rows (64,320 total). Use `is_filled = 0` when averaging NAV.",
 "- AUM exists at two levels: `fact_aum` is per fund house (9 reporting dates); `fact_performance.aum_crore` is per scheme (one snapshot).",
 "- `fact_transactions` covers 2024-01-01 to 2025-05-30; `fact_nav` covers 2022-01-03 to 2026-05-29."]
(ROOT / "data_dictionary.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("data_dictionary.md written,", len(out), "lines")
